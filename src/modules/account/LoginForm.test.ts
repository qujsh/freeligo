import { mount, flushPromises } from "@vue/test-utils";
import { QueryClient, VueQueryPlugin } from "@tanstack/vue-query";
import { defineComponent, h } from "vue";
import { afterEach, expect, it, vi } from "vitest";
import LoginForm from "./LoginForm.vue";
const { signIn } = vi.hoisted(() => ({ signIn: vi.fn().mockResolvedValue(undefined) }));
vi.mock("./session", () => ({ useSession: () => ({ signIn }) }));
afterEach(() => { vi.unstubAllGlobals(); vi.clearAllMocks(); });
it("默认不勾选，链接固定版本，接受后提交精确编号；新版本到达取消勾选", async () => {
  const docs = [{ id: 10, kind: "TERMS", version: 2, html: "terms", contentHash: "a" }, { id: 20, kind: "PRIVACY", version: 1, html: "privacy", contentHash: "b" }];
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue(new Response(JSON.stringify({ success: true, msg: docs }))));
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const Input = defineComponent({ props: ["modelValue"], emits: ["update:modelValue"], setup: (p, { emit }) => () => h("input", { "aria-label": "登录密码", value: p.modelValue, onInput: (e: Event) => emit("update:modelValue", (e.target as HTMLInputElement).value) }) });
  const wrapper = mount(LoginForm, { global: { plugins: [[VueQueryPlugin, { queryClient: client }]], components: { ElInput: Input } } });
  await flushPromises();
  await vi.waitFor(() => expect(wrapper.find('input[type="checkbox"]').exists()).toBe(true));
  expect(wrapper.get('input[type="checkbox"]').element).toHaveProperty("checked", false);
  expect(wrapper.find('a[href="/legal/terms/2"]').exists()).toBe(true);
  await wrapper.get("form").trigger("submit");
  expect(signIn).not.toHaveBeenCalled();
  expect(wrapper.get('[role="alert"]').text()).toContain("请先阅读并同意");
  await wrapper.get('input[aria-label="登录手机号"]').setValue("13900000000");
  await wrapper.get('input[aria-label="登录密码"]').setValue("test-only");
  await wrapper.get('input[type="checkbox"]').setValue(true);
  await wrapper.get("form").trigger("submit");
  expect(signIn).toHaveBeenCalledWith("13900000000", "test-only", "password", { accepted: true, termsId: 10, privacyId: 20 });
  client.setQueryData(["legal", "login-current"], [{ ...docs[0], id: 30, version: 3 }, docs[1]]);
  await flushPromises();
  expect(wrapper.get('input[type="checkbox"]').element).toHaveProperty("checked", false);
  expect(wrapper.find('a[href="/legal/terms/3"]').exists()).toBe(true);
  wrapper.unmount(); client.clear();
});
